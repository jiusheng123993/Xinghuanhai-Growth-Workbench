/**
 * Agent 确定性意图预筛（纯函数，无依赖）
 * 目的：对可规则识别的高置信度意图，在调用付费 LLM 意图分类前先用正则命中，
 * 既省一次分类调用，又消除 LLM 分类的不确定性——例如把「这是什么猫」误判为 chat，
 * 导致不调 search_breed_info、不跳品种详情页（用户「AI 识别到品种却没跳」的根因之一）。
 * 只收录高精度规则：宁可漏判（回落到 LLM 分类）也不误判（误判会污染意图路由）。
 */

/** 品种提问规则：命中即锁定 breed 意图（意图分类步骤可跳过） */
const BREED_QUESTION_PATTERNS: RegExp[] = [
  /这是什么(?:猫|狗|犬|品种|种类)/, // "这是什么猫/狗/品种"
  /这是(?:啥|什么)(?:猫|狗|犬)/,     // "这是啥猫"
  /是什么(?:猫|狗|犬|品种)/,         // "是什么猫"
  /(?:啥|什么|哪个)品种/,            // "什么品种/啥品种"
  /(?:猫|狗|犬)的品种/,              // "猫的品种"
];

/** 归一化：去空白、转小写（中文问句去空格；英文无关紧要） */
function normalize(text: string): string {
  return (text || '').replace(/\s+/g, '').toLowerCase();
}

/** 是否为品种提问（供 Agent 意图预筛使用） */
export function detectBreedQuestion(text: string): boolean {
  const t = normalize(text);
  if (!t) return false;
  return BREED_QUESTION_PATTERNS.some((p) => p.test(t));
}

// ========== 明确「记录回忆/写日记」请求（2026-09-11 新增） ==========
// 事故背景：用户说"记录回忆…"时 LLM 意图分类器返回 chat（置信度 ≥ 0.7），
// agentLoop 对 chat 意图走 tool_choice='none'（**禁用全部工具**），模型物理上无法调用
// record_memory，只会用文字回一句"好的，记下了"——用户以为记了，去「时光」却什么都没有
// （生产实测 2026-09-11 04:10 该用户 intent=chat、tool_chain 为空）。
// 本规则把这类**明确祈使请求**确定性路由到 memory 意图（走 auto + 意图提示强制调 record_memory），
// 与 detectBreedQuestion 同一模式：既省一次付费分类调用，又消除不确定性。
// 精度优先原则不变，故设三道闸：
//   ① "回忆录"（另一条产品线：回忆录视频）用负向断言 (?!录) 排除；
//   ② 疑问/求助口吻（"怎么记录回忆""存到时光线吗""保存回忆失败怎么办"）一律回落 LLM 分类——
//      memory 意图是 confidence=1.0 的硬锁 + 提示词"务必调用该工具"，误判的代价是模型把**问句本身**
//      写成一条 pet_moments 假回忆（还会挤占回忆录素材候选），远高于多花一次分类调用；
//   ③ 相邻产品线的"记录"请求（打卡/喂养/疫苗/体重/体检）同样交 LLM 判断。
// （2026-09-11 双 Agent 独立审查 P1-1 实测反例："怎么记录回忆""记录回忆在哪里看"
//   "保存回忆失败怎么办""怎么把照片存到时光线里""打卡记录能存到时光线吗""喂养记录怎么存到回忆里"
//   —— 全部为问句却会被原规则命中，故补下面两道守卫；反例已固化进 agentRuleIntent.test.ts）
const MEMORY_RECORD_QUERY_PATTERNS: RegExp[] = [
  // 疑问词：出现即说明用户在"问怎么用/能不能/会不会"，而不是在下达记录指令
  /怎么|如何|怎样|为什么|为啥|干嘛|在哪|哪里|哪儿|什么时候|是不是|是否|有没有|会不会|能不能|能否|可不可以|好不好|要不要|该不该|什么|啥|多少|多久|行不行|教程|方法是什么|功能|入口|失败|报错|没反应/,
  // A-不-A 重叠问式（"贵不贵/快不快/难不难"）——逐个列词会漏，用通用式收口（复验第 3 轮建议）
  /(.)不\1/,
  // 句尾语气词（调用前已剥掉尾部标点，因此"记录回忆吗？"同样能命中）
  // 刻意不含"吧"：祈使用"吧"很常见（"写个日记吧"），加了会把正常指令误拦；
  // "吧"只在整句以问号收尾时才算问句（见 detectMemoryRecordIntent 的 rawTailQuestion）
  /[吗呢]$/,
];

/**
 * 相邻业务线的"记录"请求（打卡/喂养/疫苗/体重/体检/驱虫/用药/回忆录）不是回忆 → 交 LLM 分类
 * 只在**命令片段**里出现才算：正文里出现"疫苗/体重/用药"恰恰是养宠回忆的高频词
 * （"记录回忆：今天带它打疫苗…"必须照常命中，否则又回到"AI 说记了其实没写"的老路）
 */
const MEMORY_RECORD_ADJACENT_PATTERNS: RegExp[] = [
  /打卡|签到|喂养|喂食|喂了|喂过|疫苗|体重|体检|驱虫|用药|回忆录/,
];

/**
 * "记录别的东西"的常见宾语 → 交 LLM 分类（这类正文若被当成回忆正文，会直接写进 pet_moments 变脏数据）
 * 与上面的区别：这些词出现在**整句任意位置**都足以判定不是回忆，故作用于整句而非命令片段。
 */
const MEMORY_RECORD_OTHER_OBJECT_PATTERNS: RegExp[] = [
  /待办|日程|行程|要点|笔记|密码|账号|单词|步骤|任务|清单|会议/,
];

const MEMORY_RECORD_PATTERNS: RegExp[] = [
  // ① 记录/保存/写下/写个 +（量词｜这/我的）? + 回忆|日记|瞬间|日常
  // （"记录回忆""写个日记""记录一条回忆""保存这段回忆""记录一下我的回忆""记录心情日记"）
  /(?:记录|记下|记一下|保存|写下|写个|写篇|写一条|写一段)(?:一下|一段|一条|一篇|一个|个|篇|段|条|这份|这段|这条|这个)?(?:我的|我们的)?(?:心情)?(?:回忆(?!录)|日记|瞬间|日常)/,
  // ② 句首裸"写日记 / 写回忆"（"写日记""写一篇日记"）
  //    必须锚定句首：否则"我写日记好几年了""它写日记一样把爪子按在纸上"这类陈述句会被误判（复验 N3）
  /^写(?:个|篇|一篇|一条|一段|一个|一下)?(?:日记|回忆(?!录))/,
  // ③ 帮我/给我/替我 + 记|写 +（下来|一下|下）? + …的事|经历|回忆|日记|瞬间|日常（"帮我记下今天的事"）
  /(?:帮|给|替)(?:我|我们)?(?:记|记录|记下|写|写下)(?:一下|下|下来)?(?:今天|今日)?(?:的)?(?:事|事情|经历|回忆(?!录)|日记|瞬间|日常)/,
  // ④ 记下/记录/写下 +（下来|来|下）? + 这|那 +（件|段|次|些）?事|经历|回忆
  // （"记下这件事：它把花瓶打碎了""记下来这件事""记录下来这件事""记下那次经历"）
  // 坑点：动词要按「记下 / 记录 / 写下」分别列出，且补语要写全「下来|来|下」——
  // 写成 (?:记|写)(?:下|录) 时，"记录下来"（记+录+下+来）会在"录"之后卡住，实测漏判（2026-09-11 审查 P2-3）。
  /(?:记下|记录|写下)(?:下来|来|下)?(?:这|那)(?:件|段|次|些)?(?:事|事情|经历|回忆(?!录)|记忆)/,
  // ⑤ 记录/记一下 + 今天|今日 + 的事|经历（"记录一下今天的事"）
  /(?:记录|记一下|记下)(?:一下)?(?:今天|今日)(?:的)?(?:事|事情|经历|回忆(?!录))/,
  // ⑥ 存进/放进/收进 + 时光|回忆|记忆（"把这段存进时光簿"）
  /(?:存|放|收)(?:进|到)(?:时光|回忆(?!录)|记忆)/,
  // ⑦ 句首祈使 + 直接接正文：这类正文没有"事/经历/回忆"关键词，靠 ①-⑥ 会漏判
  // （"帮我记一下：今天它趴在我腿上睡着了""记录下来：它今天学会握手了""记录一下它今天干的坏事"）
  // 只认句首形态 + 「冒号/结尾/这那它今天」紧跟其后，避免把正文中出现的动词或
  // "记录一下我的账号密码/待办清单"这类**记录别的东西**的陈述当成回忆指令（复验第 3 轮 H/I 组）。
  /^(?:帮我|给我|替我|请)?(?:记录|记下|记一下|记录下|写下|写一下|记录下来|记下来|写下来)(?:一下|下)?(?:[：:,，、]|$|这|那|它|他|她|今天|今日)/,
];

/**
 * 取"命令片段"：原文第一个分隔标点之前的部分
 * ⚠️ 必须在 normalize 之前切分（保留标点才能切准）——若先去标点，冒号会被吃掉、切不出片段，
 * 守卫就会退化成"扫整句"（2026-09-11 复验实测：那种写法让 11 条明确记录请求被打回 LLM）。
 * ⚠️ 分隔符必须包含逗号/顿号/空白：用户常写"记录回忆，今天它打疫苗了"，
 * 只按冒号切会让正文里的"疫苗"参与守卫判定，又把真实请求打回 LLM（复验第 3 轮建议）。
 * @param raw - 用户原始输入
 */
function commandFragment(raw: string): string {
  return (raw || '').split(/[：:，,、；;\s]/)[0];
}

/**
 * 是否为「明确要求记录一段回忆/写日记」的请求（供 Agent 意图预筛使用）
 * @param text - 用户输入
 * @returns 命中则 Agent 直接按 memory 意图路由（跳过 LLM 意图分类）
 */
export function detectMemoryRecordIntent(text: string): boolean {
  const t = normalize(text);
  if (!t) return false;
  // 守卫**只作用于"命令片段"**（冒号之前），并先剥掉尾部标点以便识别语气词：
  //  - 拿整句判守卫会把"记录回忆：今天带它打疫苗，它吓得不知道怎么好"这类**真实记录请求**
  //    打回 LLM 分类（复验实测 20 条明确请求被判掉 11 条，其中 4 条直达
  //    "chat → tool_choice='none' → 什么都没写"的原始事故路径）；
  //  - 而疑问句整类又必须拦住（复验实测 20 条里 19 条会被误判成"要记录"）。
  const head = normalize(commandFragment(text)).replace(/[。！？!?~～，,、；;]+$/, '');
  // 整句以问号收尾 + 句尾"吧" → 仍是问句（"记录回忆算隐私内容吧？"）
  const rawTailQuestion = /[？?]\s*$/.test(text || '');
  if (rawTailQuestion && /吧$/.test(head)) return false;
  if (MEMORY_RECORD_QUERY_PATTERNS.some((p) => p.test(head))) return false;
  if (MEMORY_RECORD_ADJACENT_PATTERNS.some((p) => p.test(head))) return false;
  // "记录别的东西"的宾语作用于整句：它们在正文里出现同样说明不是宠物回忆
  if (MEMORY_RECORD_OTHER_OBJECT_PATTERNS.some((p) => p.test(t))) return false;
  return MEMORY_RECORD_PATTERNS.some((p) => p.test(t));
}

// ========== 越界话题（回答边界：专门服务宠物行业） ==========
// 背景（2026-09 用户明确要求）：星河宠记定位「专门服务宠物行业」的小程序，AI 管家
// 只聊宠物/养宠相关，其余越界话题一律礼貌拒绝并拉回。此处用高精度正则做确定性拦截
// （宁可漏判、不误判）：只收录「几乎必然与宠物无关」的短语类别，且刻意排除有宠物语境
// 歧义的词——如"找对象/处对象"（=给猫找对象配种）、"减肥"（=给猫减肥）、"感冒/发烧"
// （=猫感冒）、"游戏"（=和猫玩游戏）、"八字/生肖/运势"（=宠物取名命理）。这些歧义与其余
// 长尾越界（推荐电影/人类疾病/商业模式等）交由 LLM 意图分类器的 offtopic 意图兜底。

/**
 * 与宠物无关的越界话术（按类别分组，高精度；词条均核查过宠物语境歧义）
 */
const OFFTOPIC_PATTERNS: RegExp[] = [
  // —— 恋爱/婚恋 ——
  /谈恋爱|想恋爱|恋爱了|脱单|相亲|失恋|分手|暗恋|表白|前任|网恋|异地恋|求婚|离婚|结婚|催婚/,
  // —— 学业代办（作业/论文/作文，兼容"写一篇论文/写个作业"等量词）——
  /写(?:个|篇|一篇|一下)?(?:作业|论文|作文)|做(?:个|份)?作业/,
  // —— 编程/技术（i 标志：normalize 会小写，Python/Java 需忽略大小写）——
  /写代码|写程序|写脚本|学编程|学Python|学Java|debug|代码报错|前端开发|后端开发/i,
  // —— 翻译代办 ——
  /帮我翻译|翻译成|翻译一下|英译中|中译英|翻译这段/,
  // —— 求职/职场（i 标志：PPT 等拉丁缩写忽略大小写）——
  /找工作|求职|面试|做简历|写简历|做PPT|离职|辞职|跳槽/i,
  // —— 财经/投资/博彩（i 标志：A股 等忽略大小写）——
  /股票|炒股|基金|理财|比特币|加密货币|区块链|彩票|中奖|涨停|跌停|A股|美股/i,
  // —— 天气查询 ——
  /天气预报|天气怎么样|天气如何|今日天气|明天天气/,
  // —— 时事/政治/新闻 ——
  /新闻|时政|政治|选举|特朗普|拜登|俄乌|中美关系/,
  // —— 娱乐/追剧/游戏（具体游戏名，避开"和猫玩游戏"歧义）——
  /追剧|综艺|明星|八卦|娱乐圈|王者荣耀|原神|吃鸡|游戏攻略/,
  // —— 星座/算命（避开"八字/生肖"宠物命名歧义）——
  // 单词级词条：这些词在宠物语境下也几乎必然是越界话题，直接拦截。
  /星座|算命|占卜|塔罗|风水|看手相/,
  // —— 运势（2026-09-10 修复：由单词级 /运势/ 收窄为人类语境的常用搭配）——
  // 事故背景：AI 取名·命理详情的提示词（miniapp/src/utils/namingPrompts.ts 的
  // buildDetailPrompt）含"整体运势/事业运势/感情运势/健康运势"等字样，单词级
  // /运势/ 会把这条**业务内请求**判为越界 → /api/ai/chat 直接返回 OFFTOPIC_REPLY
  // 且不调 LLM → 前端 parseDetailResult 解析失败、静默降级为本地模板文案，
  // 命理深度分析（付费能力）100% 失效（2026-09-10 实测复现）。
  // 现改为「动词 + 时间/所属 + 运势」与「时间/所属 + 的? + 运势」两类确定性问法；
  // 刻意不收录「整体/健康/事业/感情」等前缀（命理提示词用词），纯"运势"两字等
  // 长尾交给 LLM offtopic 意图分类器兜底——沿用本文件"宁可漏判不误判"的原则。
  /(?:看|算|测|查|问|求|占)(?:一?下|一卦|看|算)?(?:我的|今年|今天|今日|明天|本周|这周|本月|明年|近期|最近)?运势/,
  /(?:我的|今年|今天|今日|明天|本周|这周|本月|明年|近期|最近)的?运势/,
];

/**
 * 越界话题的固定拒绝话术（确定性输出，不依赖 LLM）
 * 措辞保持"工具助手"定位：不陪伴、不恋人化，只把话题拉回宠物健康与记录
 */
export const OFFTOPIC_REPLY =
  '我是「团团」宠物管家，只专注养宠与宠物行业相关的话题哦～恋爱、生活、工作、时事这些我不擅长，就不展开了。咱们还是聊你家毛孩子吧：给它打个卡、查查食物，或记录点今天的小事？';

/**
 * 是否为与宠物无关的越界话题（恋爱/婚恋、学业、编程、财经、天气、时事、娱乐、算命、求职等高精度类别）
 * 供 /api/agent/chat 在进入 LLM 主循环前确定性拦截（省一次付费调用 + 硬保证边界）
 *
 * ⚠️ 宠物业务自身的结构化请求（AI 取名/命理解读）会包含"运势/五行/星宿"等字样，
 * 命中越界规则会把正常业务打回拒绝话术（2026-09-10 命理详情事故），
 * 新增词条前务必用 services/__tests__/agentRuleIntent.test.ts 的
 * 「不应误伤宠物取名命理请求」用例回归一遍。
 * @param text - 用户输入
 */
export function detectOffTopic(text: string): boolean {
  const t = normalize(text);
  if (!t) return false;
  return OFFTOPIC_PATTERNS.some((p) => p.test(t));
}
