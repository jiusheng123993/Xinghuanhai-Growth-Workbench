/**
 * Agent 确定性意图预筛（纯函数，无依赖）
 * 目的：对可规则识别的高置信度意图，在调用付费 LLM 意图分类前先用正则命中，
 * 既省一次分类调用，又消除 LLM 分类的不确定性——例如把「这是什么猫」误判为 chat，
 * 导致不调 search_breed_info、不跳品种详情页（用户「AI 识别到品种却没跳」的根因之一）。
 * 只收录高精度规则：宁可漏判（回落到 LLM 分类）也不误判（误判会污染意图路由）。
 */

/** 品种提问规则：命中即锁定 breed 意图（意图分类步骤可跳过） */
const BREED_QUESTION_PATTERNS: RegExp[] = [
  /这是什么(?:猫|狗|犬|品种|种类)/, // "这是什么猫/狗/品种"
  /这是(?:啥|什么)(?:猫|狗|犬)/,     // "这是啥猫"
  /是什么(?:猫|狗|犬|品种)/,         // "是什么猫"
  /(?:啥|什么|哪个)品种/,            // "什么品种/啥品种"
  /(?:猫|狗|犬)的品种/,              // "猫的品种"
];

/** 归一化：去空白、转小写（中文问句去空格；英文无关紧要） */
function normalize(text: string): string {
  return (text || '').replace(/\s+/g, '').toLowerCase();
}

/** 是否为品种提问（供 Agent 意图预筛使用） */
export function detectBreedQuestion(text: string): boolean {
  const t = normalize(text);
  if (!t) return false;
  return BREED_QUESTION_PATTERNS.some((p) => p.test(t));
}

// ========== 越界话题（回答边界：专门服务宠物行业） ==========
// 背景（2026-09 用户明确要求）：星河宠记定位「专门服务宠物行业」的小程序，AI 管家
// 只聊宠物/养宠相关，其余越界话题一律礼貌拒绝并拉回。此处用高精度正则做确定性拦截
// （宁可漏判、不误判）：只收录「几乎必然与宠物无关」的短语类别，且刻意排除有宠物语境
// 歧义的词——如"找对象/处对象"（=给猫找对象配种）、"减肥"（=给猫减肥）、"感冒/发烧"
// （=猫感冒）、"游戏"（=和猫玩游戏）、"八字/生肖"（=宠物取名命理）。这些歧义与其余
// 长尾越界（推荐电影/人类疾病/商业模式等）交由 LLM 意图分类器的 offtopic 意图兜底。

/**
 * 与宠物无关的越界话术（按类别分组，高精度；词条均核查过宠物语境歧义）
 */
const OFFTOPIC_PATTERNS: RegExp[] = [
  // —— 恋爱/婚恋 ——
  /谈恋爱|想恋爱|恋爱了|脱单|相亲|失恋|分手|暗恋|表白|前任|网恋|异地恋|求婚|离婚|结婚|催婚/,
  // —— 学业代办（作业/论文/作文，兼容"写一篇论文/写个作业"等量词）——
  /写(?:个|篇|一篇|一下)?(?:作业|论文|作文)|做(?:个|份)?作业/,
  // —— 编程/技术（i 标志：normalize 会小写，Python/Java 需忽略大小写）——
  /写代码|写程序|写脚本|学编程|学Python|学Java|debug|代码报错|前端开发|后端开发/i,
  // —— 翻译代办 ——
  /帮我翻译|翻译成|翻译一下|英译中|中译英|翻译这段/,
  // —— 求职/职场（i 标志：PPT 等拉丁缩写忽略大小写）——
  /找工作|求职|面试|做简历|写简历|做PPT|离职|辞职|跳槽/i,
  // —— 财经/投资/博彩（i 标志：A股 等忽略大小写）——
  /股票|炒股|基金|理财|比特币|加密货币|区块链|彩票|中奖|涨停|跌停|A股|美股/i,
  // —— 天气查询 ——
  /天气预报|天气怎么样|天气如何|今日天气|明天天气/,
  // —— 时事/政治/新闻 ——
  /新闻|时政|政治|选举|特朗普|拜登|俄乌|中美关系/,
  // —— 娱乐/追剧/游戏（具体游戏名，避开"和猫玩游戏"歧义）——
  /追剧|综艺|明星|八卦|娱乐圈|王者荣耀|原神|吃鸡|游戏攻略/,
  // —— 星座/算命/运势（避开"八字/生肖"宠物命名歧义）——
  /星座|运势|算命|占卜|塔罗|风水|看手相/,
];

/**
 * 越界话题的固定拒绝话术（确定性输出，不依赖 LLM）
 * 措辞保持"工具助手"定位：不陪伴、不恋人化，只把话题拉回宠物健康与记录
 */
export const OFFTOPIC_REPLY =
  '我是「团团」宠物管家，只专注养宠与宠物行业相关的话题哦～恋爱、生活、工作、时事这些我不擅长，就不展开了。咱们还是聊你家毛孩子吧：给它打个卡、查查食物，或记录点今天的小事？';

/**
 * 是否为与宠物无关的越界话题（恋爱/婚恋、学业、编程、财经、天气、时事、娱乐、算命、求职等高精度类别）
 * 供 /api/agent/chat 在进入 LLM 主循环前确定性拦截（省一次付费调用 + 硬保证边界）
 * @param text - 用户输入
 */
export function detectOffTopic(text: string): boolean {
  const t = normalize(text);
  if (!t) return false;
  return OFFTOPIC_PATTERNS.some((p) => p.test(t));
}
