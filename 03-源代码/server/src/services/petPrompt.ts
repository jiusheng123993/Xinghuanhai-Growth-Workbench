/**
 * 宠物生图提示词公共模块
 *
 * 把项目提示词库《宠物回忆录-提示词库.md》中适用于「AI 生图」的规范固化成可复用函数，
 * 所有调用 Seedream 等文生图/图生图的服务（全家福 / 头像 / 2D 表情包）统一引用，
 * 防止各自写一套提示词导致质量参差、再次翻车。依据的提示词库章节：
 * - §0.6 全局角色锁定表：数量敏感角色显式声明、易跑偏角色显式排除（禁止模型加戏）
 * - §四 角色一致性模板：face/fur/body keep（毛色/花纹/体型/五官锁定）
 * - 宠物主体描述规范：品种具体化，品种缺失时兜底
 *
 * ⚠️ 关键安全规则：提示词中绝不写宠物名字！
 * 名字对文生图模型是噪声甚至灾难——猫咪叫「烧鸡」会被画成一只烧鸡，
 * 且会覆盖参考图把主体画错。名字只用于入库记录，不进 prompt。
 */

/** 物种中文名（dog → 狗狗，其余一律视为猫咪） */
export function petSpeciesLabel(species: string): string {
  return species === 'dog' ? '狗狗' : '猫咪';
}

/** 品种缺失时的兜底描述（避免提示词出现空串或 undefined） */
export const PET_BREED_FALLBACK = '毛茸茸的';

/**
 * 「不确定品种」标记词：前端 unknown_mix 的展示文案（及同类口语词）。
 * 这些词对文生图模型是无效噪声甚至指令污染（「不确定」可能被当成指令执行，
 * 与 2026-08-24「烧鸡」被画成鸡同类风险的低危版），命中时按品种缺失兜底。
 */
const UNKNOWN_BREED_MARKERS = ['不确定品种', '混血', '串串'];

/**
 * 单只宠物主体描述：一只英短猫咪 / 一只母英短猫咪 / 一只毛茸茸的猫咪
 * @param breed - 品种，可为空（档案未填）
 * @param species - 物种（dog / cat / 其他）
 * @param genderLabel - 可选性别前缀（公 / 母 / 空）
 * @returns 主体描述，绝不包含宠物名字
 */
export function petSubjectText(breed: string | null | undefined, species: string, genderLabel = ''): string {
  // 品种是用户自由文本：先清洗换行/控制字符再截断，防止污染提示词结构或注入额外指令
  const b = (breed || '').replace(/[\r\n\t]+/g, ' ').trim().slice(0, 20);
  // 「不确定品种」等标记命中时按品种缺失兜底，避免「一只不确定品种的猫咪」进入提示词
  const isUnknownBreed = UNKNOWN_BREED_MARKERS.some((m) => b.includes(m));
  return b && !isUnknownBreed
    ? `一只${genderLabel}${b}${petSpeciesLabel(species)}`
    : `一只${genderLabel}${PET_BREED_FALLBACK}${petSpeciesLabel(species)}`;
}

/**
 * 角色一致性约束（仅图生图/有参考照片时使用）
 * 对应提示词库 §四「角色一致性模板」：face keep / fur keep / body keep
 * 多图/参考图合成时，外观以参考照片为准，禁止模型自由发挥
 */
export const PET_IDENTITY_KEEP =
  '以参考照片为准，保持宠物的毛色、花纹、体型、五官与参考图完全一致，不改变外貌';

/**
 * 主体锁定（单只场景）：防模型加戏/多画/混入其他主体
 * 对应提示词库 §0.6「数量敏感角色显式声明」
 */
export const PET_ONLY_ONE =
  '画面中只出现这一只宠物，不要出现其他动物、人物或食物';

/** 中文序数（左起第一只 / 第二只…；超过十只用阿拉伯数字兜底，实际全家福成员远达不到） */
const CN_ORDINALS = ['一', '二', '三', '四', '五', '六', '七', '八', '九', '十'];

/**
 * 名字 → 外貌指代 转译器：允许用户用自己的话提到宠物名字，但名字绝不进提示词
 *
 * 用户心智模型是「烧鸡在左边追蝴蝶」，而生图模型听到「烧鸡」就会画一只烧鸡
 * （2026-08-24 真实事故）。本函数在服务端清洗阶段把已知宠物名替换为
 * 「那只英短猫咪」（单只）/「左起第二只橘猫」（多只，配合全家福排位顺序）
 * 式的外貌指代——用户零学习成本，模型收到的是纯外貌语言。
 *
 * @param raw - 用户自由文本（应已过基础清洗）
 * @param pets - 已知宠物集合（名字是有限集合，来自档案）；多只时数组顺序=画面从左到右顺序
 * @returns 转译后的文本；无命中原样返回
 */
export function translatePetNames(
  raw: string,
  pets: Array<{ name?: string | null; breed?: string | null; species?: string | null }>,
): string {
  if (!raw) return raw;
  // 收集有效名字（去空白、限长、按名字去重），并记录序号用于多宠方位前缀
  const nameMap = new Map<string, { breed: string | null; species: string; ordinal: number }>();
  let ordinal = 0;
  for (const p of pets) {
    const name = (p.name || '').trim();
    if (!name || name.length > 20 || nameMap.has(name)) continue;
    ordinal += 1;
    nameMap.set(name, { breed: p.breed ?? null, species: p.species ?? '', ordinal });
  }
  if (nameMap.size === 0) return raw;

  const multi = nameMap.size > 1;
  // 长名字优先替换，避免短名是长名子串时误伤（如「小猫」⊂「小猫咪」）
  const names = [...nameMap.keys()].sort((a, b) => b.length - a.length);
  let out = raw;
  for (const name of names) {
    const info = nameMap.get(name)!;
    // 外貌指代复用主体描述模块（含品种兜底与「不确定品种」防污染），去掉「一只」前缀拼方位词
    const subject = petSubjectText(info.breed, info.species).replace(/^一只/, '');
    const prefix = multi ? `左起第${CN_ORDINALS[info.ordinal - 1] ?? info.ordinal}只` : '那只';
    out = out.split(name).join(`${prefix}${subject}`);
  }
  return out;
}

/* ==========================================================================
 * 命名句式（结构性）清洗
 *
 * 为什么需要它：translatePetNames 是「白名单」思路——拿宠物档案里的名字去文本里替换，
 * 它有个结构性盲区：**LLM 自己编造出来的名字，它拦不住**。例如分镜脚本里写
 * 「一只叫小橘的猫在窗台上」，「小橘」不在任何宠物档案里，白名单匹配不到，整句原样进
 * 提示词；而同型于「烧鸡」事故的风险（猫被画成橘子 / 橘色物体）就回来了。
 *
 * 下面这组常量与函数不依赖任何名字清单，只靠**句法结构**判断「这里在给某个主体起名」，
 * 命中后把「命名框架 + 名字」一起删掉，只留下句子原本就有的中性指代。
 * ========================================================================== */

/** 宠物类名词词头：只有「叫 X 的 ___」里的 ___ 确实是只宠物，才敢认定 X 是名字 */
const PET_NOUN_HEAD = '(?:猫咪|猫猫|喵喵|狗狗|狗子|宠物|毛孩子|小猫|小狗|猫|狗|犬)';

/**
 * 显式命名标记（**刻意不含裸「叫」**）。
 * 「叫」是中文高频动词（叫我过去 / 有人在叫卖 / 狗在叫），只有「叫 X 的猫」这种带上
 * 「的 + 宠物名词」的句法才能证明它在起名，所以裸「叫」单独交给 NAMING_MODIFIER_RE 判定。
 * 数组按长度倒序拼进正则，保证「名字叫作」先于「名字叫」、「名叫」先于「名为」被匹配。
 */
const NAME_MARKERS: string[] = [
  '名字叫作',
  '名字叫做',
  '名字唤作',
  '名字唤做',
  '名字叫',
  '名字是',
  '名字为',
  '昵称叫作',
  '昵称叫做',
  '昵称叫',
  '昵称是',
  '昵称为',
  '小名唤作',
  '小名唤做',
  '小名叫',
  '小名是',
  '小名唤',
  '外号叫',
  '外号是',
  '绰号叫',
  '绰号是',
  '代号叫',
  '代号是',
  '取名叫',
  '取名为',
  '起名叫',
  '起名为',
  '名叫',
  '名为',
  '名唤',
  '叫作',
  '叫做',
  '唤作',
  '唤做',
  '称呼为',
  '称呼叫',
  // 「取名字」是「给猫取名字」这种普通说法，不是命名句式，故用否定前瞻排除「字」
  '取名(?!字)',
  '起名(?!字)',
].sort((a, b) => b.length - a.length);

/**
 * 名字候选段（正则片段）：1~8 个字符
 * - **不含空白、中英标点与「的」**：既让名字边界正确（「叫小明的猫」不会连定语一起吞），
 *   也避免候选段跨过标点把两个句子粘在一起
 * - **不以人称代词开头**：这是「他叫我过去」「老板叫你过去一下」的主要防线——「叫我」后面
 *   本来就没有「的 + 宠物名词」，代词否定再兜一层，彻底断掉「叫我」被当名字的可能
 * - **上限 8 字**：超过 8 字的候选段不当作名字，避免把一整句话当名字删掉
 * - 西文双引号写成 \u0022 转义，避免源码里出现裸双引号（等价写法，正则语义一致）
 */
const NAME_SEG =
  '(?!(?:我们|你们|他们|大家|谁|我|你|您|他|她|它|咱|俺))' +
  '[^\\s，。！？；：、,.!?…·「」『』“”‘’\u0022\'（）()《》〈〉【】\\[\\]{}<>的]{1,8}';

/**
 * 裸「叫」后面的**动词补语**白名单式排除：「叫」当动词用时，紧跟的多是补语而非名字。
 * 不排除的话会出现真误伤：「被叫醒的猫咪」→「被猫咪」、「被邻居叫走的狗」→「被邻居狗」、
 * 「隔壁叫春的猫」→「隔壁猫」。这些补语一律不当作名字候选，宁可漏掉这几个名字。
 * ⚠️ 只作用于裸「叫」这一支，显式命名标记（名叫 / 叫作 / 唤作…）不受影响。
 */
const CALL_COMPLEMENTS =
  '过去|过来|回去|起来|出来|进来|醒|走|来|去|回|出|进|上|下|住|停|开|卖|号|门|春';

/**
 * 句式一（定语式）：「<显式标记 | 裸「叫」> + 名字 + 的」，整段删除，保留后面的宠物名词。
 * - 「一只叫小橘的猫在窗台上」→ 删「叫小橘的」→「一只猫在窗台上」
 * - 「名叫旺财的那只猫」→ 删「名叫旺财的」→「那只猫」（「的」随命名框架一起删，不留悬空的「的」）
 * - 「唤作小黑的猫」→ 删「唤作小黑的」→「猫」
 *
 * 末尾用**前瞻**（不消费）确认「的」后面确实接着宠物名词，允许 0~2 个字的外貌修饰
 * （「的橘猫」「的那只猫」）；只有这样才能认定这是命名结构，否则一律不动。
 * 前置的否定前瞻挡掉「的时候」这类桥接误伤：「他叫小黑的时候猫会来」不动
 * ——「的时候」是时间状语，不是定语。
 */
const NAMING_MODIFIER_RE = new RegExp(
  `(?:${NAME_MARKERS.join('|')}|叫(?!(?:${CALL_COMPLEMENTS})))${NAME_SEG}的` +
    '(?!(?:时候|地方|事情|东西|日子|原因|办法|问题))' +
    `(?=[^\\s，。！？；：、,.!?…的]{0,2}?${PET_NOUN_HEAD})`,
  'g',
);

/**
 * 句式二（谓语式）：「<可选的 的> + 显式标记 + 名字」，名字之后必须是标点或句末。
 * - 「这只狗名字是旺财」→ 删「名字是旺财」→「这只狗」（连同前面那个「的」一起删，不留「这只狗的」）
 * - 「那只猫叫作咪咪，正在睡觉」→ 删「叫作咪咪」→「那只猫，正在睡觉」（停顿逗号保留）
 * - 「昵称是团子」→ 删光，返回空串
 *
 * ⚠️ 要求右边界是标点或句末，是为了不把「名叫小明的学生」啃成「明的学生」——
 * 右边界不成立时整条不匹配（宁可漏，不可误伤）。
 */
const NAMING_CLAUSE_RE = new RegExp(
  `(的)?(?:${NAME_MARKERS.join('|')})${NAME_SEG}(?=[，。！？；：、,.!?…\\s]|$)([，、；：。！？]?)`,
  'g',
);

/**
 * 命名句式结构性清洗：拦下「白名单拦不住」的编造名字
 *
 * 与 translatePetNames 是互补关系，不是替代关系：本函数只认句法结构（「叫 X 的猫」
 * 「名字是 X」），对没有命名框架的名字无能为力；translatePetNames 只认档案里的名字，
 * 对编造的名字无能为力。两者都跑，才是完整防线。
 *
 * 推荐调用顺序（已由测试锁住）：**先 stripNamingPhrases，再 translatePetNames**。
 * 理由是先去命名框架，白名单那一遍看到的就是剩下的普通文本，不会出现
 * 「名叫那只英短猫咪的猫」这种别扭的中间态；反过来调用最终结果同样不含名字
 * （测试里也锁了），故顺序错了不会漏名字，只是中间态更难看。
 *
 * ⚠️ 本函数只删名字与命名框架，**不往文本里加任何东西**（不产出生图噪声）。
 *
 * @param raw - 待清洗文本（用户文案 / LLM 分镜脚本等）
 * @returns 清洗后的文本；未命中命名句式时原样返回（幂等）
 */
export function stripNamingPhrases(raw: string): string {
  if (!raw) return raw;

  // 第一遍：定语式——删「<标记|叫>名字的」，保留其后的宠物名词
  let out = raw.replace(NAMING_MODIFIER_RE, '');

  // 第二遍：谓语式——删「[的]<标记>名字」，并按上下文决定紧随其后的标点去留
  out = out.replace(
    NAMING_CLAUSE_RE,
    (
      _match: string,
      _leadingDe: string | undefined,
      trailing: string | undefined,
      offset: number,
      whole: string,
    ): string => {
      // 删除点前一个字符：用来判断删完会不会前后各留一个相同的句末标点（「。。」残渣）
      const before = offset > 0 ? whole[offset - 1] : '';
      // 整段就在开头（前面什么都没有）时，它后面的标点也跟着失去了依附，一并带走：
      // 「名字是旺财。今天天气好」→「今天天气好」，否则会剩一个句首悬空的「。」
      if (offset === 0) return '';
      // 标点一律保留，只清「删除点两侧是同一个标点」这种自产残渣：
      // 「汪汪。名字是旺财。今天」→「汪汪。今天」
      // 为什么不吃掉逗号：吃掉会把「这只狗名字是旺财，那只猫叫小黑」粘成
      // 「这只狗那只猫叫小黑」——两个主体糊成一团，比留一个停顿逗号更糟（宁可不改坏）。
      if (trailing && trailing === before) return '';
      return trailing ?? '';
    },
  );

  // 收尾①：名字删掉后可能剩下孤零零的停顿标点（落在句首、跟在句末标点之后、或连成一串），
  // 这类才是残渣（如「，很乖的狗」），清掉；句中的正常逗号不动
  out = out.replace(/(^|[。！？…；：])[，、；：]+/g, '$1');
  // 收尾②：删除点在空白旁时可能留下多余空格，折叠一下（不改动换行结构）
  return out.replace(/[ \t]{2,}/g, ' ').trim();
}
